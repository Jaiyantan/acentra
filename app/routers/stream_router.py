"""
Real-time Streaming API Router (WebSocket & Server-Sent Events)
Saveetha Medical College and Hospital (SMCH) Operations Engine
"""

import asyncio
import json
from fastapi import APIRouter, WebSocket, WebSocketDisconnect, Query
from fastapi.responses import StreamingResponse
from typing import Optional, List, Dict, Any
from app.simulation.events_bus import event_bus

router = APIRouter(tags=["Real-time Live Streams (WebSockets & SSE)"])

@router.websocket("/ws/live")
async def websocket_live_events(websocket: WebSocket):
    """
    WebSocket endpoint streaming all hospital events in real-time.
    Connect here to get live second-by-second updates across all 16 departments.
    """
    await websocket.accept()
    queue = event_bus.subscribe()
    try:
        # Send recent events immediately upon connection
        recent = event_bus.get_recent_events(limit=15)
        for ev in reversed(recent):
            await websocket.send_text(json.dumps(ev))

        while True:
            event = await queue.get()
            await websocket.send_text(json.dumps(event))
    except WebSocketDisconnect:
        pass
    except Exception:
        pass
    finally:
        event_bus.unsubscribe(queue)

@router.websocket("/ws/icu")
async def websocket_icu_stream(websocket: WebSocket):
    """
    WebSocket endpoint streaming high-frequency multi-bed ICU bedside telemetry
    (HR, BP, SpO2, EtCO2, CVP, Temp, Cardiac rhythm).
    """
    await websocket.accept()
    queue = event_bus.subscribe_icu()
    try:
        while True:
            telemetry = await queue.get()
            await websocket.send_text(json.dumps(telemetry))
    except WebSocketDisconnect:
        pass
    except Exception:
        pass
    finally:
        event_bus.unsubscribe_icu(queue)

@router.get("/api/stream/events", summary="Server-Sent Events (SSE) stream of hospital events")
async def sse_event_stream():
    """
    Server-Sent Events (SSE) HTTP stream for browser applications.
    """
    async def event_generator():
        queue = event_bus.subscribe()
        try:
            # Yield initial connect packet
            yield f"data: {json.dumps({'type': 'connected', 'hospital': 'Saveetha Medical College and Hospital (SMCH)'})}\n\n"
            while True:
                event = await queue.get()
                yield f"data: {json.dumps(event)}\n\n"
        except asyncio.CancelledError:
            pass
        finally:
            event_bus.unsubscribe(queue)

    return StreamingResponse(event_generator(), media_type="text/event-stream")

@router.get("/api/stream/recent", summary="Fetch recent hospital events from ring buffer")
def get_recent_events(
    limit: int = Query(50, ge=1, le=200),
    department: Optional[str] = Query(None, description="Filter by department"),
    severity: Optional[str] = Query(None, description="Filter by severity: INFO, SUCCESS, WARNING, CRITICAL, EMERGENCY")
):
    """
    Returns the latest events generated by the live hospital simulator.
    """
    events = event_bus.get_recent_events(limit=limit, department=department, severity=severity)
    return {"count": len(events), "events": events}
